export type CopyKey = keyof typeof en;

export function parseLocale(value: string | undefined): Locale {
  return value === "th" ? "th" : "en";
}

export async function getLocale(): Promise<Locale> {
  const jar = await cookies();
  return parseLocale(jar.get(LOCALE_COOKIE)?.value);
}

export function t(locale: Locale, key: CopyKey, vars?: Record<string, string | number>): string {
  const template = (locale === "th" ? th : en)[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function countText(locale: Locale, kind: "lead" | "contact", count: number): string {
  const key = count === 1 ? (`count.${kind}` as const) : (`count.${kind}s` as const);
  return t(locale, key, { count });
}

export function stageText(locale: Locale, stage: string): string {
  if (stage === "QUALIFIED" || stage === "PROPOSAL" || stage === "WON" || stage === "LOST" || stage === "NEW") {
    return t(locale, `stage.${stage}`);
  }
  return stage;
}

export function sourceText(locale: Locale, source: string): string {
  if (source === "WEBSITE" || source === "MANUAL" || source === "LINE") return t(locale, `source.${source}`);
  return source;
}
